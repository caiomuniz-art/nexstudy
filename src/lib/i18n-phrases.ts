const MONTHS: Record<string, string> = {
  janeiro: "January",
  fevereiro: "February",
  março: "March",
  abril: "April",
  maio: "May",
  junho: "June",
  julho: "July",
  agosto: "August",
  setembro: "September",
  outubro: "October",
  novembro: "November",
  dezembro: "December",
};

const WEEKDAYS: Record<string, string> = {
  domingo: "Sunday",
  "segunda-feira": "Monday",
  "terça-feira": "Tuesday",
  "quarta-feira": "Wednesday",
  "quinta-feira": "Thursday",
  "sexta-feira": "Friday",
  sábado: "Saturday",
};

function applyPatterns(value: string): string | null {
  const greeting = /^(Bom dia|Boa tarde|Boa noite), (.+)$/.exec(value);
  if (greeting) {
    const hello = PHRASES[greeting[1] ?? ""] ?? greeting[1];
    return `${hello}, ${greeting[2]}`;
  }

  const progress = /^(\d+) de (\d+) tarefas concluídas\.$/.exec(value);
  if (progress) return `${progress[1]} of ${progress[2]} tasks completed.`;

  const studied = /^Estudo nesta semana: (.+)\.$/.exec(value);
  if (studied) return `Study this week: ${studied[1]}.`;

  const destroy = /^Excluir “(.+)”\?$/.exec(value);
  if (destroy) return `Delete “${destroy[1]}”?`;

  const destroyTask = /^Excluir “(.+)”\? Esta ação não pode ser desfeita\.$/.exec(value);
  if (destroyTask) return `Delete “${destroyTask[1]}”? This cannot be undone.`;

  const linked = /^“(.+)” está ligada a (\d+) tarefas, (\d+) avaliações e (\d+) sessões\. Esses registros serão desvinculados e não serão apagados\.$/.exec(value);
  if (linked) return `“${linked[1]}” is linked to ${linked[2]} tasks, ${linked[3]} assessments, and ${linked[4]} sessions. Those records will be unlinked and will not be deleted.`;

  const overdue = /^(.+) venceu em (.+)\.$/.exec(value);
  if (overdue) return `${overdue[1]} was due on ${overdue[2]}.`;

  const due = /^(.+) vence em (.+)\.$/.exec(value);
  if (due) return `${due[1]} is due on ${due[2]}.`;

  const planned = /^(.+) está previsto para (.+)\.$/.exec(value);
  if (planned) return `${planned[1]} is scheduled for ${planned[2]}.`;

  const noDate = /^(.+) ainda não tem data de entrega\.$/.exec(value);
  if (noDate) return `${noDate[1]} does not have a due date yet.`;

  const happens = /^(.+) acontece em (.+)\.$/.exec(value);
  if (happens) return `${happens[1]} takes place on ${happens[2]}.`;

  const marked = /^(.+) está marcada para (.+)\.$/.exec(value);
  if (marked) return `${marked[1]} is set for ${marked[2]}.`;

  const weekOf = /^Semana de (\d{2}\/\d{2}\/\d{4})$/.exec(value);
  if (weekOf) return `Week of ${weekOf[1]}`;

  const room = /^Sala (.+)$/.exec(value);
  if (room) return `Room ${room[1]}`;

  const page = /^Página (\d+) de (\d+) · (\d+) tarefas$/.exec(value);
  if (page) return `Page ${page[1]} of ${page[2]} · ${page[3]} tasks`;

  const summary = /^(\d+) tarefas \((\d+) em aberto\) · (\d+) avaliações · (\d+) sessões · (.+) estudados$/.exec(value);
  if (summary) return `${summary[1]} tasks (${summary[2]} open) · ${summary[3]} assessments · ${summary[4]} sessions · ${summary[5]} studied`;

  const sessions = /^(\d+) sessões concluídas na conta\.$/.exec(value);
  if (sessions) return `${sessions[1]} completed sessions on the account.`;

  const theme = /^Tema: (claro|escuro|sistema)$/.exec(value);
  if (theme) {
    const names = { claro: "light", escuro: "dark", sistema: "system" };
    return `Theme: ${names[theme[1] as "claro" | "escuro" | "sistema"]}`;
  }

  const longDate = /^(domingo|segunda-feira|terça-feira|quarta-feira|quinta-feira|sexta-feira|sábado), (\d{1,2}) de (janeiro|fevereiro|março|abril|maio|junho|julho|agosto|setembro|outubro|novembro|dezembro) de (\d{4})$/i.exec(value);
  if (longDate) {
    const weekday = WEEKDAYS[(longDate[1] ?? "").toLowerCase()] ?? longDate[1];
    const month = MONTHS[(longDate[3] ?? "").toLowerCase()] ?? longDate[3];
    return `${weekday}, ${month} ${longDate[2]}, ${longDate[4]}`;
  }

  const monthYear = /^(janeiro|fevereiro|março|abril|maio|junho|julho|agosto|setembro|outubro|novembro|dezembro) de (\d{4})$/i.exec(value);
  if (monthYear) return `${MONTHS[(monthYear[1] ?? "").toLowerCase()] ?? monthYear[1]} ${monthYear[2]}`;

  const dayMonth = /^(\d{1,2}) de (janeiro|fevereiro|março|abril|maio|junho|julho|agosto|setembro|outubro|novembro|dezembro) de (\d{4})$/i.exec(value);
  if (dayMonth) return `${MONTHS[(dayMonth[2] ?? "").toLowerCase()] ?? dayMonth[2]} ${dayMonth[1]}, ${dayMonth[3]}`;

  return null;
}

function translateCore(value: string): string {
  const exact = PHRASES[value];
  if (exact) return exact;
  const patterned = applyPatterns(value);
  if (patterned) return patterned;
  if (value.includes(" · ")) {
    const parts = value.split(" · ").map((part) => PHRASES[part] ?? applyPatterns(part) ?? part);
    const joined = parts.join(" · ");
    if (joined !== value) return joined;
  }
  return value;
}

export function translateText(value: string) {
  const match = /^(\s*)([\s\S]*?)(\s*)$/.exec(value);
  if (!match) return value;
  const lead = match[1] ?? "";
  const core = match[2] ?? "";
  const trail = match[3] ?? "";
  if (!core) return value;
  const mapped = translateCore(core);
  if (mapped === core) return value;
  return `${lead}${mapped}${trail}`;
}
